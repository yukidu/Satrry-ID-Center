-- 0006: CENTRAL-owned, private cross-App token verification (not Battery D1).
-- Additive to 0004. Requires verified Central identity_users.
-- Strictly private Service Binding only; no public introspection or token issuer.
-- This migration never grants access, issues a token, or populates real users.

CREATE TABLE IF NOT EXISTS central_brand_authorizations (
 user_id TEXT NOT NULL REFERENCES identity_users(user_id) ON DELETE RESTRICT,
 brand_scope TEXT NOT NULL CHECK(brand_scope='starry'),
 granted_at_ms INTEGER NOT NULL CHECK(granted_at_ms>0),
 revoked_at_ms INTEGER,
 authorization_reference TEXT NOT NULL CHECK(length(trim(authorization_reference))>=8),
 PRIMARY KEY(user_id,brand_scope),
 CHECK(revoked_at_ms IS NULL OR revoked_at_ms>=granted_at_ms)
);
CREATE INDEX IF NOT EXISTS idx_central_brand_authorizations_active
 ON central_brand_authorizations(brand_scope,revoked_at_ms);

-- The token is a random 256-bit opaque bearer generated by a trusted CENTRAL
-- issuer. Only its SHA-256 hash is stored, never the raw token.
-- CENTRAL issuer must re-check the authenticated user and Starry brand grant
-- before issuance; implementing the issuer is a separate audited work package.
CREATE TABLE IF NOT EXISTS central_service_access_tokens (
 token_sha256 TEXT PRIMARY KEY NOT NULL
  CHECK(length(token_sha256)=64 AND token_sha256 NOT GLOB '*[^0-9a-f]*'),
 user_id TEXT NOT NULL REFERENCES identity_users(user_id) ON DELETE RESTRICT,
 source_session_hash TEXT NOT NULL REFERENCES auth_sessions(session_id_hash) ON DELETE RESTRICT,
 brand_scope TEXT NOT NULL CHECK(brand_scope='starry'),
 audience TEXT NOT NULL CHECK(audience='starry-battery'),
 issued_auth_version INTEGER NOT NULL CHECK(issued_auth_version>=1),
 issued_at_ms INTEGER NOT NULL CHECK(issued_at_ms>0),
 expires_at_ms INTEGER NOT NULL,
 revoked_at_ms INTEGER,
 issuer_reference TEXT NOT NULL CHECK(length(trim(issuer_reference))>=8),
 CHECK(expires_at_ms>issued_at_ms AND expires_at_ms-issued_at_ms<=900000),
 CHECK(revoked_at_ms IS NULL OR revoked_at_ms>=issued_at_ms)
);
CREATE INDEX IF NOT EXISTS idx_central_service_tokens_session ON central_service_access_tokens(source_session_hash,revoked_at_ms);
CREATE INDEX IF NOT EXISTS idx_central_service_tokens_owner
 ON central_service_access_tokens(user_id,revoked_at_ms);
CREATE INDEX IF NOT EXISTS idx_central_service_tokens_expiry
 ON central_service_access_tokens(expires_at_ms);
